const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'dmd-aging-split-'));
process.env.DMD_DB_PATH=path.join(dir,'synthetic.db');process.env.NODE_ENV='test';
require('./seed-epacket.cjs');
const {db}=require('../src/lib/db.ts'),{createUser}=require('../src/lib/auth.ts');
const {accountFinancials,financialAction,localDay,shiftDay,allocateFIFO}=require('../src/lib/credit.ts');
const {finalizeStatement,statementPreview}=require('../src/lib/statements-v2.ts');
let checks=0;const eq=(a,b,m)=>{assert.deepEqual(a,b,m);checks++};
try{
const admin=createUser({username:'split.admin',display_name:'Admin',role:'ADMIN',password:'Synthetic123!'});
const sales=createUser({username:'split.sales',display_name:'Sales',role:'SALES',password:'Synthetic123!'});
const client=createUser({username:'split.client',display_name:'Client',role:'CLIENT',password:'Synthetic123!',sales_user_id:sales.id});
const today=localDay(),old=shiftDay(today,-40),future=shiftDay(today,30);
// Only this freshly created temporary fixture is backdated.
db.exec('DROP TRIGGER statement_v2_epoch_immutable_UPDATE; DROP TRIGGER statement_v2_events_immutable_UPDATE');
db.prepare('UPDATE statement_v2_epoch SET started_at=? WHERE id=1').run(old+'T00:00:00Z');
db.prepare("INSERT INTO ledger_entries(client_user_id,entry_type,direction,amount) VALUES (?,'ADDITIONAL_FEE','DEBIT',100)").run(client.id);
db.prepare('UPDATE statement_v2_events SET posted_at=? WHERE client_id=?').run(old+'T01:00:00Z',client.id);
financialAction(admin,client.id,{action:'configure',credit_limit:500,credit_term_days:14,purchase_locked:false});
finalizeStatement(admin,client.id,old,old);
let f=accountFinancials(client.id,{readOnly:true});
eq(f.debt_age.status,'OVERDUE','Old Balance is overdue');
const ledgerBefore=db.prepare('SELECT COUNT(*) n FROM ledger_entries').get().n;
financialAction(admin,client.id,{action:'debt',amount:40,deadline:future,reason:'Synthetic partial transfer',request_key:'split-partial'});
f=accountFinancials(client.id,{readOnly:true});
eq(f.net_balance_cents,-6000,'Partial transfer restores Balance once');
eq(f.debt_age.amount_cents,6000,'Only residual Balance ages');
eq(f.debt_age.status,'OVERDUE','Residual old Balance still overdue');
financialAction(admin,client.id,{action:'debt',amount:60,deadline:future,reason:'Synthetic full transfer',request_key:'split-full'});
f=accountFinancials(client.id,{readOnly:true});
eq(f.net_balance_cents,0,'Full transfer clears negative Balance');
eq(f.debt_age.status,'CLEAR','Old Statement cannot age transferred Debt');
eq(f.purchase_blocked,false,'Future Debt permits buying');
eq(db.prepare('SELECT COUNT(*) n FROM ledger_entries').get().n,ledgerBefore,'No fake Payment or credit');
const preview=statementPreview(admin,client.id,shiftDay(old,1),today);
eq(preview.movements.filter(e=>e.source==='credit_debts').reduce((s,e)=>s+e.debt_cents,0),10000,'Next Statement records transfer');
eq(preview.closing.balance_cents,0,'Statement signed Balance agrees');
eq(preview.closing.debt_cents,10000,'Statement Debt agrees');
db.prepare('UPDATE credit_debts SET deadline=? WHERE client_id=?').run(shiftDay(today,-1),client.id);
eq(accountFinancials(client.id,{readOnly:true}).reasons.includes('Debt quá hạn'),true,'Own Debt deadline blocks');
financialAction(admin,client.id,{action:'extend_debt',debt_id:f.debts[0].id,deadline:future,reason:'Synthetic extension'});
eq(accountFinancials(client.id,{readOnly:true}).purchase_blocked,false,'Extension releases only Debt deadline block');
db.prepare("INSERT INTO ledger_entries(client_user_id,entry_type,direction,amount) VALUES (?,'PAYMENT','CREDIT',25)").run(client.id);
allocateFIFO(client.id);f=accountFinancials(client.id,{readOnly:true});
eq(f.debts[0].outstanding_cents,7500,'Partial Payment settles principal');
eq(f.net_balance_cents,0,'Debt repayment does not restore buying room twice');
eq(f.debt_age.status,'CLEAR','Debt payment cannot revive old Statement age');
console.log('BALANCE DEBT AGING SPLIT PASS ('+checks+' assertions)');
}finally{db.close();fs.rmSync(dir,{recursive:true,force:true})}
